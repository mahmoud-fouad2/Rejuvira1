/** Canonical CMS aliases take precedence; unknown pages receive no guessed copy. */
export function landingSearchProfile(slug: string, seoSlug?: string | null) {
  const find = (key?: string | null) =>
    key && Object.hasOwn(landingSearchProfiles, key)
      ? landingSearchProfiles[key]
      : null;
  return find(seoSlug) || find(slug) || null;
}
